export function fill(template, ...args) {
  return String(template ?? "").replace(/\$(\d+)/g, (_, n) => {
    const value = args[Number(n) - 1];
    return value == null ? "" : String(value);
  });
}

/** Browser tag, legacy zh-Hant/zh-Hans, or a catalog code → catalog code. */
export function resolveLocale(input) {
  const raw = String(input || "").trim().replace(/_/g, "-");
  if (CATALOG[raw]) return raw;
  const lower = raw.toLowerCase();
  if (lower === "zh-hant" || lower.startsWith("zh-hant-")) return "zh-TW";
  if (lower === "zh-hans" || lower.startsWith("zh-hans-")) return "zh-CN";
  if (lower.startsWith("zh")) {
    return /^zh-(hant|tw|hk|mo)(?:-|$)/.test(lower) ? "zh-TW" : "zh-CN";
  }
  if (lower.startsWith("pt")) return "pt-BR";
  const base = lower.split("-")[0];
  const map = { en: "en", ja: "ja", ko: "ko", es: "es", fr: "fr", de: "de" };
  return map[base] || "en";
}

export function intlTag(locale) {
  return resolveLocale(locale);
}

export function text(locale, key) {
  const code = resolveLocale(locale);
  const table = CATALOG[code] || CATALOG.en;
  const value = table[key];
  if (typeof value === "string" && value) return value;
  const fallback = CATALOG.en[key];
  return typeof fallback === "string" ? fallback : "";
}

/** Chrome messages.json entry. $1 becomes $ARG1$ with a placeholder. */
export function chromeMessage(template) {
  const textValue = String(template ?? "");
  const nums = [...textValue.matchAll(/\$(\d+)/g)].map((match) => Number(match[1]));
  const unique = [...new Set(nums)].sort((a, b) => a - b);
  if (!unique.length) return { message: textValue };
  const names = { 1: "arg1", 2: "arg2", 3: "arg3" };
  let message = textValue;
  const placeholders = {};
  for (const n of unique) {
    const name = names[n] || `arg${n}`;
    message = message.replaceAll(`$${n}`, `$${name.toUpperCase()}$`);
    placeholders[name] = { content: `$${n}` };
  }
  return { message, placeholders };
}

export function messagesJson(locale) {
  const table = CATALOG[locale];
  const out = {};
  for (const [key, value] of Object.entries(table)) {
    out[key] = chromeMessage(value);
  }
  return out;
}
